export async function searchAnilist(query: string) {
  const clean = query.trim().toLowerCase();
  if (!clean) return [];

  const graphQLQuery = `
    query ($search: String) {
      Page (page: 1, perPage: 10) {
        media (search: $search, type: MANGA, sort: POPULARITY_DESC) {
          id
          title {
            romaji
            english
            native
          }
          countryOfOrigin
          coverImage {
            large
            extraLarge
          }
          bannerImage
          genres
          chapters
          volumes
          status
          startDate {
            year
          }
          description
        }
      }
    }
  `;

  try {
    const res = await fetch('https://graphql.anilist.co', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Accept': 'application/json',
      },
      body: JSON.stringify({
        query: graphQLQuery,
        variables: { search: query }
      })
    });

    if (res.ok) {
      const data = await res.json();
      const mediaList = data?.data?.Page?.media || [];

      return mediaList.map((m: AnilistMediaResult) => {
        let format: ComicFormat = 'MANGA';
        if (m.countryOfOrigin === 'KR') format = 'MANHWA';
        else if (m.countryOfOrigin === 'CN') format = 'MANHUA';

        const cover = m.coverImage?.extraLarge || m.coverImage?.large || 'https://images.unsplash.com/photo-1544716278-ca5e3f4abd8c?q=80&w=600&auto=format&fit=crop';
        const banner = m.bannerImage || cover;

        return {
          id: m.id,
          title: m.title.english || m.title.romaji || 'Untitled',
          romajiTitle: m.title.romaji,
          nativeTitle: m.title.native || undefined,
          comicFormat: format,
          coverImage: cover,
          bannerImage: banner,
          genres: m.genres || ['Fantasy'],
          totalChapters: m.chapters || undefined,
          totalVolumes: m.volumes || undefined,
          status: m.status || 'RELEASING',
          releaseYear: m.startDate?.year ? String(m.startDate.year) : undefined,
          synopsis: m.description ? m.description.replace(/<[^>]+>/g, '') : ''
        };
      });
    }
  } catch (err) {
    console.warn('AniList GraphQL request failed, using fallback:', err);
  }

  // Fallback
  return FALLBACK_READ_DATABASE.filter(item =>
    item.title.toLowerCase().includes(clean) ||
    item.nativeTitle?.toLowerCase().includes(clean) ||
    item.genres.some(g => g.toLowerCase().includes(clean))
  );
}

export async function fetchAnilistDetails(id: number): Promise<{
  status?: string;
  chapters?: number | null;
  volumes?: number | null;
} | null> {
  const graphQLQuery = `
    query ($id: Int) {
      Media (id: $id, type: MANGA) {
        status
        chapters
        volumes
      }
    }
  `;

  try {
    const res = await fetch('https://graphql.anilist.co', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Accept': 'application/json',
      },
      body: JSON.stringify({
        query: graphQLQuery,
        variables: { id }
      })
    });

    if (res.ok) {
      const data = await res.json();
      return data?.data?.Media || null;
    }
  } catch (err) {
    console.warn('Failed to fetch AniList details for ID:', id, err);
  }

  // Fallback check
  const fallback = FALLBACK_READ_DATABASE.find(item => item.id === id);
  if (fallback) {
    return {
      status: fallback.status,
      chapters: fallback.totalChapters
    };
  }

  return null;
}
